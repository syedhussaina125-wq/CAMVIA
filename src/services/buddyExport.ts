import type { AskCamviaExportData } from './askCamvia'

export function exportToCsv(data: AskCamviaExportData): void {
  const sanitize = (value: unknown): string => {
    if (value === null || value === undefined) return ''
    const str = String(value).replace(/"/g, '""')
    return /[",\n\r]/.test(str) ? `"${str}"` : str
  }

  const headerLine = data.columns.map(sanitize).join(',')
  const rowLines = data.rows.map((row) => row.map(sanitize).join(','))
  const csvContent = '\uFEFF' + [headerLine, ...rowLines].join('\r\n')

  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' })
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = `${data.filename || 'camvia-export'}.csv`
  document.body.appendChild(anchor)
  anchor.click()
  document.body.removeChild(anchor)
  URL.revokeObjectURL(url)
}

export function exportToHtmlPrint(data: AskCamviaExportData): void {
  const printWindow = window.open('', '_blank', 'width=800,height=600')
  if (!printWindow) return

  const rowsHtml = data.rows
    .map(
      (row) =>
        `<tr>${row.map((cell) => `<td style="padding: 6px 12px; border-bottom: 1px solid #e2e8f0;">${cell ?? ''}</td>`).join('')}</tr>`,
    )
    .join('')

  const headersHtml = data.columns
    .map(
      (col) =>
        `<th style="padding: 8px 12px; border-bottom: 2px solid #cbd5e1; text-align: left; background: #f8fafc; font-size: 13px;">${col}</th>`,
    )
    .join('')

  const html = `
    <!DOCTYPE html>
    <html>
      <head>
        <title>${data.title}</title>
        <style>
          body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; padding: 24px; color: #1e293b; }
          h2 { margin-top: 0; color: #0f172a; }
          table { width: 100%; border-collapse: collapse; margin-top: 16px; font-size: 12px; }
          .footer { margin-top: 24px; font-size: 11px; color: #64748b; }
        </style>
      </head>
      <body>
        <h2>${data.title}</h2>
        <p style="font-size: 12px; color: #64748b;">Generated by CAMVIA Buddy · ${new Date().toLocaleDateString()}</p>
        <table>
          <thead><tr>${headersHtml}</tr></thead>
          <tbody>${rowsHtml}</tbody>
        </table>
        <div class="footer">Confidential · Authorized School Records Only</div>
        <script>
          window.onload = function() { window.print(); }
        </script>
      </body>
    </html>
  `

  printWindow.document.write(html)
  printWindow.document.close()
}
